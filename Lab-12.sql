	RNO INT PRIMARY KEY,
	NAME VARCHAR(20) NOT NULL,
	BRANCH VARCHAR(20) DEFAULT 'CE'
);
CREATE TABLE RESULT(
	RESULTID INT PRIMARY KEY,
	SPI DECIMAL(4,2) CHECK (SPI BETWEEN 0 AND 10),
	RNO INT FOREIGN KEY REFERENCES STUDENT_INFO(RNO)
);
